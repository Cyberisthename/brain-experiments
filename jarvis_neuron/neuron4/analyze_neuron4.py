import json, sys, numpy as np
from collections import defaultdict
sys.path.insert(0, "."); import n3lib as N
P = [json.loads(l) for l in open("results/per_question.jsonl")]
S = ["exact","rag","A","D_auto","E_auto","E_oracle"]
stor = json.load(open("results/storage.json")); clf = json.load(open("results/classifier.json"))
rng = np.random.default_rng(0)
def ans(r, s): return r[s]["answer"] != "ABSTAIN"
def aurc(R, s):
    A = sorted([r for r in R if ans(r, s)], key=lambda r: (-r[s]["confidence"], N.h01(r["qid"], r["seed"])))
    if not A: return None
    e = np.cumsum([1 - r[s]["correct"] for r in A]) / np.arange(1, len(A) + 1); return float(e.mean())
def met(R, s):
    n = len(R); a = [r for r in R if ans(r, s)]; g = [r for r in R if r["gold"] != "ABSTAIN"]; ab = [r for r in R if r["gold"] == "ABSTAIN"]
    mh = [r for r in R if r["kind"] == "multi_hop_3"]
    return dict(n=n, coverage=len(a)/n, ans_coverage=sum(ans(r, s) for r in g)/max(1, len(g)),
        sel_acc=sum(r[s]["correct"] for r in a)/max(1, len(a)), correct=sum(r[s]["correct"] for r in R)/n,
        abstain=1-len(a)/n, conf_wrong=sum(r[s]["wrong"] for r in R)/n,
        approp_abst=sum(r[s]["abstain"] for r in ab)/max(1, len(ab)), multi_hop=sum(r[s]["correct"] for r in mh)/max(1, len(mh)),
        aurc=aurc(R, s), storage=float(np.mean([x[s] for x in stor])))
def by_cluster(R, f):
    d = defaultdict(list)
    for r in R: d[(r["seed"], r["cluster"])].append(f(r))
    return d
def ni_p(R, s1, s2, margin=-0.10, B=2000):
    G = [r for r in R if r["gold"] != "ABSTAIN"]
    d = by_cluster(G, lambda r: int(ans(r, s1)) - int(ans(r, s2))); ks = list(d); arr = [np.array(d[k], float) for k in ks]
    sums = np.array([a.sum() for a in arr]); lens = np.array([len(a) for a in arr]); bs = []
    for _ in range(B):
        i = rng.integers(0, len(ks), len(ks)); bs.append(sums[i].sum()/lens[i].sum())
    bs = np.array(bs); return float(sums.sum()/lens.sum()), float((np.sum(bs <= margin) + 1)/(B + 1)), [float(np.percentile(bs, 2.5)), float(np.percentile(bs, 97.5))]
out = {}
R1 = [r for r in P if r["corpus"] == 1]; R2 = [r for r in P if r["corpus"] == 2]
for nm, R in (("corpus1_heldout_projects", R1), ("corpus2_cross_source", R2)):
    out[nm] = {s: met(R, s) for s in S}
    out[nm + "_by_kind"] = {k: {s: met([r for r in R if r["kind"] == k], s) for s in S} for k in sorted({r["kind"] for r in R})}
    out[nm + "_per_seed_cwrong"] = {s: [met([r for r in R if r["seed"] == sd], s)["conf_wrong"] for sd in sorted({r["seed"] for r in R})] for s in S}
tests = []
for tgt in ("E_auto", "D_auto"):
    T = []
    for comp in ("A", "exact"):
        obs, p = N.cluster_signflip(by_cluster(R1, lambda r: r[tgt]["wrong"] - r[comp]["wrong"]), 10000, rng)
        T.append(dict(test=f"{tgt} conf_wrong < {comp}", diff=obs, p=p, direction_ok=obs < 0))
    for comp in ("A", "exact"):
        obs, p, ci = ni_p(R1, tgt, comp)
        T.append(dict(test=f"{tgt} answerable coverage non-inferior to {comp} (margin -10pp)", diff=obs, p=p, ci95=ci))
    adj = N.holm([t["p"] for t in T])
    for t, a in zip(T, adj): t["p_holm"] = a; t["pass"] = bool(a < 0.05 and t.get("direction_ok", True))
    out[("PRIMARY_" if tgt == "E_auto" else "secondary_") + tgt] = T
out["primary_supported"] = all(t["pass"] for t in out["PRIMARY_E_auto"])
out["classifier"] = dict(mean_test_f1=float(np.mean([c["test_f1"] for c in clf])), mean_prec=float(np.mean([c["test_prec"] for c in clf])),
                         mean_rec=float(np.mean([c["test_rec"] for c in clf])), bytes=clf[0]["clf_bytes"])
out["n_questions"] = dict(c1=len(R1), c2=len(R2), seeds=len({r["seed"] for r in P}))
json.dump(out, open("results/analysis.json", "w"), indent=1)
f = lambda v: "-" if v is None else f"{v:.3f}"
L = ["# NEURON-4 RESULTS (auto-generated by analyze_neuron4.py)\n", f"Questions: {out['n_questions']}\n"]
for nm in ("corpus1_heldout_projects", "corpus2_cross_source"):
    L += [f"\n## {nm}\n", "| system | coverage | answerable cov | selective acc | correct | abstain | conf-wrong | approp. abstain | multi-hop | AURC | storage B |", "|"+"---|"*11]
    for s in S:
        m = out[nm][s]; L.append(f"| {s} | {f(m['coverage'])} | {f(m['ans_coverage'])} | {f(m['sel_acc'])} | {f(m['correct'])} | {f(m['abstain'])} | {f(m['conf_wrong'])} | {f(m['approp_abst'])} | {f(m['multi_hop'])} | {f(m['aurc'])} | {m['storage']:.0f} |")
    L += ["", "conf-wrong by kind:", "| kind | " + " | ".join(S) + " |", "|"+"---|"*(len(S)+1)]
    for k, d in out[nm + "_by_kind"].items(): L.append(f"| {k} (n={d['A']['n']}) | " + " | ".join(f"{f(d[s]['conf_wrong'])} / cov {f(d[s]['coverage'])}" for s in S) + " |")
for key in ("PRIMARY_E_auto", "secondary_D_auto"):
    L += [f"\n## {key} (Holm within family)"] + [f"- {t['test']}: diff {t['diff']:+.3f}, p {t['p']:.4f}, Holm {t['p_holm']:.4f} -> {'PASS' if t['pass'] else 'FAIL'}" for t in out[key]]
L += [f"\n**Primary hypothesis supported: {out['primary_supported']}**", f"\nClassifier (test projects): {out['classifier']}"]
open("RESULTS.md", "w").write("\n".join(L)); print("\n".join(L))
